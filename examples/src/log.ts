/** docs/ATTACK_LOG.md: one row per attack, expected vs actual. Codes and tx links only. */
import { ATTACKS, LEASE_CALLS, LEASE_ENDPOINTS, expectText } from "./cases.ts";
import type { Row } from "./run.ts";

const cell = (s: string) => s.replace(/\|/gu, "\\|").replace(/\n/gu, " ");

export interface LogInfo {
  readonly when: string;
  readonly contract: string;
  readonly account: string;
  readonly leaseId: string;
  readonly commit: string;
}

const HEADER = `# Prompt-injection attack log

Generated by \`pnpm --filter @keylease/examples attack\` (examples/src/attack.ts). Each row is an
instruction an attacker planted for the agent, what the agent then tried with its lease, what KeyLease must
do, and what it did. NEAR testnet, the low-value demo key on the mock API; the log keeps refusal codes,
HTTP status and transaction links only, never a response body or a key.

The lease under test: ${String(LEASE_CALLS)} calls on ${LEASE_ENDPOINTS.map((e) => `\`${e}\``).join(" and ")} (the second
endpoint mirrors request headers, key included, to show the tripwire).
`;

const TABLE = `| # | Injected instruction | Agent tried | Expected | Actual | Tx | Result |
| - | -------------------- | ----------- | -------- | ------ | -- | ------ |`;

export function logMarkdown(info: LogInfo, rows: readonly Row[]): string {
  const passed = rows.filter((r) => r.pass).length;
  const lines = rows.map(
    (r) =>
      `| ${r.id} | ${cell(r.injected)} | \`${cell(r.tried)}\` | ${cell(r.expected)} | ${cell(r.actual)} | ${r.tx ? `[tx](https://testnet.nearblocks.io/txns/${r.tx})` : "-"} | ${r.pass ? "PASS" : "**FAIL**"} |`,
  );
  return `${HEADER}
Run: ${info.when}, contract \`${info.contract}\`, agent \`${info.account}\`, lease ${info.leaseId}, commit \`${info.commit}\`.
**${String(passed)}/${String(rows.length)} as expected.**

${TABLE}
${lines.join("\n")}
`;
}

/** The plan, before any testnet run: expected results only. */
export function planMarkdown(): string {
  const lines = ATTACKS.map(
    (a) =>
      `| ${a.id} | ${cell(a.injected)} | \`${cell(`${a.method} ${a.endpoint}`)}\` | ${cell(expectText(a.expect))} | not run yet | - | - |`,
  );
  return `${HEADER}
**Not run yet.** The operator box runs it on testnet (docs/VERIFY.md, "Attack run") and the actual results
replace this table.

${TABLE}
${lines.join("\n")}
`;
}
